        }
        // A single late basic-attack press may carry through the tail of a
        // released LMB or Q. The intent never replaces a still-visible
        // Attack/Cast body, is never saved, and spends nothing until accepted.
        public const float AttackBufferWindow = .16f;
        // A dodge press in the final cooldown frames should still be a dodge.
        // No stamina, invulnerability or movement begins before Dash() accepts it.
        public const float DodgeBufferWindow = .14f;
        private sealed class DodgeIntent
        {
            public float remaining;
            public Point direction;
        }
        private DodgeIntent bufferedDodge;
        // Renderers can display the accepted input without owning its clock
        // or creating a new serialized gameplay state.
        public bool DodgeRootReady
        {
            // Match Dash's physical CanStand guard. A tide/gate may have
            // sealed the previously legal floor since the key was queued.
            get { return mode=="world"&&!Dying&&CanStand(Position); }
        }
        public bool DodgeQueued
        {
            get { return bufferedDodge!=null&&DodgeRootReady; }
        }
        // Snapshot the FIRST accepted defensive tap for world feedback.
        // This is read-only; showing the marker cannot reset its 140ms
        // deadline, change collision, or grant invulnerability.
        public Point DodgeQueuedDirection
        { get { return bufferedDodge==null?new Point():bufferedDodge.direction; } }
        // The HUD offers the same bounded late-ready window for cooldown,
        // hit recovery and hit-stop as keyboard/gamepad. Never claim a queued
        // dodge is payable when GameCore would reject the input.
        public bool CanBufferDodge
        {
            get {
                float readyDelay=Math.Max(hitStop,Math.Max(dashCooldown,playerHitTime));
                return DodgeRootReady && bufferedDodge==null &&
                    readyDelay>.00001f &&
                    readyDelay<=DodgeBufferWindow+.00001f &&
                    save.energy >= (Relic(2)?25:20);
            }
        }
        private void ClearBufferedDodge() { bufferedDodge = null; }
        public void ClearBufferedCombatInputs()
        {
            ClearBufferedDodge();ClearBufferedSkill();ClearBufferedAttack();
        }
        private void QueueLateDodge(Point direction)
        {
            if(dashCooldown > DodgeBufferWindow + .00001f)return;
            // Key repeat or rapid second taps are NOT another physical
            // dodge. Retain the initial aim and original 140ms deadline;
            // a held button must never move the dodge vector at the final
            // cooldown frame or keep stale immunity queued indefinitely.
            if(bufferedDodge!=null)return;
            // Latest valid dodge press supersedes earlier buffered attacks
            // or Q. Otherwise a paid skill could fire during dodge cooldown
            // and be cancelled before its actual contact frame.
            ClearBufferedSkill();ClearBufferedAttack();
            bufferedDodge = new DodgeIntent {
                remaining=DodgeBufferWindow,
                direction=direction.Length>.1f?direction.Normalized:aim
            };
        }
        private void TickBufferedDodge(float dt,float readyDelay)
        {
            DodgeIntent intent=bufferedDodge;
            if(intent==null)return;
            // A once-legal queued escape cannot be spent from suddenly
            // sealed terrain or retain a false blue world marker until its
            // cooldown expires. The next genuinely legal tap may requeue.
            if(!DodgeRootReady){ClearBufferedDodge();return;}
            float remaining=intent.remaining;
            intent.remaining-=dt;
            if(dashCooldown<=.00001f&&playerHitTime<=.00001f&&
                hitStop<=.00001f&&readyDelay<=remaining+.00001f&&
                !Dying&&mode=="world")
            {
                // Clear BEFORE dispatch: the accepted dodge cancels the active
                // attack/skill and all other pending intents exactly once.
                ClearBufferedDodge();
                Dash(intent.direction);
            }
            else if(intent.remaining<=.00001f||Dying||mode!="world")
                ClearBufferedDodge();
        }
        private sealed class AttackIntent
        {
            public float remaining;
            public Point direction;
            public Point? target;
            public int weapon, profession, style, technique;
        }
        private AttackIntent bufferedAttack;
        // The world cue reads this exact accepted GameCore intent. It never
        // anticipates damage, moves the canonical hero, or extends a queue.
        public bool AttackQueued { get { return bufferedAttack != null; } }
        // Presentation reads the FIRST accepted held-LMB intent, not the
        // player's moving cursor. Neither property starts or extends a hit.
        // Returning an empty value after dispatch/cancellation prevents
        // stale world reticles across dodge, damage, profile or room changes.
        public Point AttackQueuedDirection
        { get { return bufferedAttack==null?new Point():bufferedAttack.direction; } }
        public Point? AttackQueuedTarget
        { get { return bufferedAttack==null?(Point?)null:bufferedAttack.target; } }
        private void ClearBufferedAttack() { bufferedAttack = null; }
        private void QueueLateAttack(Point direction)
        {
            ActorAction action = playerAction;
            if (action == null ||
                (action.kind != "attack" && action.kind != "skill") ||
                !action.released || playerHitTime > 0 ||
                dashTime > 0 || bufferedSkill != null) return;
            // A held or repeatedly tapped LMB must not re-open its old
            // 160ms deadline, steal the first press's direction/target or
            // queue a second hit. Only explicit Q / Dash / profile changes
            // may supersede this committed pending action.
            if (bufferedAttack != null) return;
            float untilReady = Math.Max(attackCooldown, Math.Max(0, action.duration - action.elapsed));
            if (untilReady > AttackBufferWindow + .00001f) return;
            Point facing = direction.Length > .05f ? direction.Normalized : aim;
            bufferedAttack = new AttackIntent { remaining = AttackBufferWindow,
                direction = facing, target = aimTarget, weapon = save.weapon,
                profession = save.profession, style = Style, technique = save.technique };
        }
        private void TickBufferedAttack(float dt, float readyDelay)
        {
            AttackIntent intent = bufferedAttack;
            if (intent == null) return;
            float previousRemaining = intent.remaining;
            intent.remaining -= dt;
            if (bufferedSkill != null || intent.weapon != save.weapon ||
                intent.profession != save.profession || intent.style != Style ||
                intent.technique != save.technique)
            { ClearBufferedAttack(); return; }
            // Compare readiness with the window *before* this simulation step
            // so a valid 30/50ms boundary input is neither lost nor extended.
            if (attackCooldown <= .00001f && playerAction == null &&
                !ActionTransitionBlocked && readyDelay <= previousRemaining + .00001f)
            {
                ClearBufferedAttack();
                Point? liveTarget = aimTarget;
                try { aimTarget = intent.target; Attack(intent.direction); }
                finally { aimTarget = liveTarget; }
            }
            else if (intent.remaining <= .00001f) ClearBufferedAttack();
        }
        public bool ActionTransitionBlocked
        {
            get { return dashTime > 0 || hitStop > 0 || playerHitTime > 0 || playerAction != null && PlayerPhase != ActionPhase.Recovery; }
        }
        public void ClearBufferedSkill() { bufferedSkill = null; }
        private float SkillReadyDelay()
        {
            float delay = Math.Max(dashTime, playerHitTime);
            ActorAction action = playerAction;
            if (action != null)
            {
                // The queued action may not replace the current full-body
                // sprite at the earlier damage/recovery boundary. Wait until
                // the current authored animation duration has actually elapsed.
                float actionDelay = Math.Max(0, action.duration - action.elapsed);
                if (!action.released) actionDelay += playerHitTime;
                delay = Math.Max(delay, actionDelay);
            }
            return delay;
        }
        private void TickBufferedSkill(float dt, float readyDelay)
        {
            SkillIntent intent = bufferedSkill;
            if (intent == null) return;
            // A contact reached during this tick may have started hit stop.
            // Preserve that pose; dispatch before the next held basic attack.
            float remaining = intent.remaining;
            intent.remaining -= dt;
            // Recovery may fall inside the final valid tick. Compare its actual
            // boundary with the old lifetime, rather than losing Q at 30 fps.
            if (playerAction == null && !ActionTransitionBlocked &&
                readyDelay <= remaining + .00001f)
                StartSkill(intent.direction, intent.target);
            else if (intent.remaining <= .00001f) ClearBufferedSkill();
        }
